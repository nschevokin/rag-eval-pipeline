import pytest

from rag.ingest.discover import DiscoveryError, discover, toc_links, write_sources

BASE = "https://www.postgresql.org/docs/16/"

CHAPTER = """
<html><body><div id="docContent"><div class="chapter" id="INDEXES">
<div class="toc"><p><strong>Table of Contents</strong></p>
<dl class="toc">
<dt><span class="sect1"><a href="indexes-intro.html">11.1. Introduction</a></span></dt>
<dt><span class="sect1"><a href="indexes-types.html">11.2. Index Types</a></span></dt>
<dd><dl>
<dt><span class="sect2"><a href="indexes-types.html#BTREE">11.2.1. B-Tree</a></span></dt>
<dt><span class="sect2"><a href="indexes-types.html#HASH">11.2.2. Hash</a></span></dt>
</dl></dd>
<dt><span class="sect1"><a href="../15/indexes-old.html">older</a></span></dt>
<dt><span class="sect1"><a href="https://example.com/x.html">external</a></span></dt>
<dt><span class="sect1"><a href="logo.png">image</a></span></dt>
</dl></div>
<p>Body text with a <a href="sql-select.html">link that is not in the table of contents</a>.</p>
</div></div></body></html>
"""


def test_toc_links_keep_chapter_and_pages_in_order_without_fragments():
    assert toc_links(CHAPTER, BASE + "indexes.html") == [
        BASE + "indexes.html",
        BASE + "indexes-intro.html",
        BASE + "indexes-types.html",
    ]


def test_discover_dedupes_across_chapters():
    pages = {BASE + "a.html": CHAPTER.encode(), BASE + "b.html": CHAPTER.encode()}
    urls = discover([BASE + "a.html", BASE + "b.html"], lambda u: pages[u])
    assert urls == [
        BASE + "a.html",
        BASE + "indexes-intro.html",
        BASE + "indexes-types.html",
        BASE + "b.html",
    ]


def test_every_bad_chapter_is_reported_and_nothing_is_returned():
    def fetch(url: str) -> bytes:
        if url.endswith("good.html"):
            return CHAPTER.encode()
        raise RuntimeError("404 Not Found")

    with pytest.raises(DiscoveryError) as err:
        discover([BASE + "good.html", BASE + "bad1.html", BASE + "bad2.html"], fetch)
    assert len(err.value.problems) == 2
    assert "bad1.html" in err.value.problems[0]


def test_sources_file_round_trips_through_the_reader(tmp_path):
    from rag.ingest.manifest import read_sources

    path = tmp_path / "sources.txt"
    urls = [BASE + "a.html", BASE + "b.html"]
    write_sources(path, urls, [BASE + "a.html"])
    assert read_sources(path) == urls
    assert path.read_text().startswith("# Generated by")

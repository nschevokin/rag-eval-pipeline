import json
from pathlib import Path

from rag.evaluate.metrics import RETRIEVAL_METRICS

HEADER = (
    "| Index preset | Retriever | Index id | Chunks | "
    + " | ".join(m.replace("_at_", "@") for m in RETRIEVAL_METRICS)
    + " | Build s | p95 ms |"
)


def ablation_rows(evidence_dir: Path, split: str = "dev") -> list[dict]:
    rows = []
    for path in sorted((evidence_dir / "evals").glob(f"{split}-*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        if data.get("metrics", {}).get("generator"):
            continue
        rows.append({**data, "file": path.name})
    rows.sort(key=lambda r: (-r["metrics"].get("ndcg_at_10", 0.0), r["file"]))
    return rows


def ablation_markdown(evidence_dir: Path, split: str = "dev") -> str:
    rows = ablation_rows(evidence_dir, split)
    lines = [
        f"# Retrieval ablation ({split} set)",
        "",
        "Generated by `rag report ablation` from `evidence/evals/`. Do not edit by hand.",
        "One machine; see the README for its description.",
        "",
        HEADER,
        "|" + "---|" * (HEADER.count("|") - 1),
    ]
    for r in rows:
        labels = r.get("labels", {})
        metrics = " | ".join(f"{r['metrics'][m]:.3f}" for m in RETRIEVAL_METRICS)
        lines.append(
            f"| {labels.get('index', '?')} | {labels.get('retriever', r['retriever'].get('name'))} "
            f"| `{r['index_id']}` | {r.get('n_chunks', '')} | {metrics} "
            f"| {r['timing']['build_seconds']:.1f} | {r['timing']['p95_ms']:.1f} |"
        )
    if not rows:
        lines.append("| no evaluations yet |" + " |" * (HEADER.count("|") - 2))
    lines.append("")
    lines.append("Source files: " + ", ".join(f"`{r['file']}`" for r in rows) if rows else "")
    return "\n".join(lines).rstrip() + "\n"

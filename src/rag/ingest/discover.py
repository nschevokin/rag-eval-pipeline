from collections.abc import Callable, Iterable
from pathlib import Path
from urllib.parse import urldefrag, urljoin, urlparse

from bs4 import BeautifulSoup

Fetcher = Callable[[str], bytes]


class DiscoveryError(RuntimeError):
    def __init__(self, problems: list[str]) -> None:
        self.problems = problems
        super().__init__("could not read every chapter page:\n  " + "\n  ".join(problems))


def toc_links(html: str, page_url: str) -> list[str]:
    soup = BeautifulSoup(html, "html.parser")
    base = urlparse(page_url)
    directory = base.path.rsplit("/", 1)[0] + "/"
    found = [page_url]
    for toc in soup.find_all(class_="toc"):
        for anchor in toc.find_all("a", href=True):
            url, _ = urldefrag(urljoin(page_url, anchor["href"]))
            parsed = urlparse(url)
            if (
                parsed.netloc != base.netloc
                or not parsed.path.startswith(directory)
                or not parsed.path.endswith(".html")
            ):
                continue
            if url not in found:
                found.append(url)
    return found


def discover(chapter_urls: Iterable[str], fetcher: Fetcher) -> list[str]:
    urls: list[str] = []
    problems: list[str] = []
    for chapter in chapter_urls:
        try:
            html = fetcher(chapter).decode("utf-8", errors="replace")
        except Exception as exc:
            problems.append(f"{chapter}: {exc}")
            continue
        for url in toc_links(html, chapter):
            if url not in urls:
                urls.append(url)
    if problems:
        raise DiscoveryError(problems)
    return urls


def write_sources(path: Path, urls: list[str], chapters: list[str]) -> None:
    header = [
        "# Generated by `rag corpus discover` from corpus/chapters.txt. Edit chapters.txt instead.",
        f"# {len(urls)} pages from {len(chapters)} chapters. Read once by `rag corpus init`.",
        "",
    ]
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join([*header, *urls]) + "\n", encoding="utf-8")
